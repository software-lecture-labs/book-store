-- Transactional outbox of order events (ADR-0022). A row is written in the same transaction as
-- the order; the relay hands it on and fills published_at. Each event type has its own columns.
CREATE TABLE order_event_types (
    code VARCHAR(30) PRIMARY KEY
);

INSERT INTO order_event_types (code) VALUES ('ORDER_PLACED'), ('ORDER_STATUS_CHANGED');

CREATE TABLE order_outbox (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type   VARCHAR(30)    NOT NULL,
    order_number CHAR(14)       NOT NULL,
    user_id      BIGINT         NULL,
    -- ORDER_PLACED
    total        DECIMAL(12, 2) NULL,
    currency     CHAR(3)        NULL,
    -- ORDER_STATUS_CHANGED
    from_status  VARCHAR(20)    NULL,
    to_status    VARCHAR(20)    NULL,
    occurred_at  TIMESTAMP(6)   NOT NULL,
    published_at TIMESTAMP(6)   NULL,
    CONSTRAINT fk_order_outbox_type FOREIGN KEY (event_type) REFERENCES order_event_types (code),
    CONSTRAINT fk_order_outbox_from FOREIGN KEY (from_status) REFERENCES order_statuses (code),
    CONSTRAINT fk_order_outbox_to FOREIGN KEY (to_status) REFERENCES order_statuses (code)
);

CREATE INDEX ix_order_outbox_pending ON order_outbox (published_at, id);
